from datetime import datetime, timezone

from app.simulator.schemas import (
    EventSeverity,
    EventSource,
    MetricProfile,
    ScenarioDefinition,
    ScenarioDifficulty,
    ScenarioEventSpec,
    ScenarioPackage,
)


def _event(
    offset: int,
    source: EventSource,
    service: str,
    message: str,
    correlation_id: str,
    severity: EventSeverity = EventSeverity.INFO,
    failure_injection: bool = False,
) -> ScenarioEventSpec:
    return ScenarioEventSpec(
        offset_seconds=offset,
        source=source,
        service_id=service,
        severity=severity,
        message=message,
        correlation_id=correlation_id,
        failure_injection=failure_injection,
    )


def _metric(
    service: str,
    name: str,
    unit: str,
    baseline: float,
    peak: float,
    start: int,
    end: int,
) -> MetricProfile:
    return MetricProfile(
        service_id=service,
        metric_name=name,
        unit=unit,
        baseline_value=baseline,
        peak_value=peak,
        change_start_seconds=start,
        change_end_seconds=end,
    )


def _package(
    scenario_id: str,
    title: str,
    description: str,
    difficulty: ScenarioDifficulty,
    services: tuple[str, ...],
    events: tuple[ScenarioEventSpec, ...],
    metrics: tuple[MetricProfile, ...],
    resolution_offset: int,
    runbook: str,
    report: str,
    actions: tuple[str, ...],
) -> ScenarioPackage:
    scenario = ScenarioDefinition(
        scenario_id=scenario_id,
        title=title,
        description=description,
        difficulty=difficulty,
        affected_services=services,
        events=events,
        metrics=metrics,
    )
    return ScenarioPackage(
        scenario=scenario,
        started_at=datetime(2026, 6, 15, 12, 0, tzinfo=timezone.utc),
        resolution_offset_seconds=resolution_offset,
        runbook=runbook,
        incident_report=report,
        resolution_record={
            "record_type": "synthetic_resolution",
            "status": "resolved",
            "actions": list(actions),
            "synthetic": True,
        },
    )


